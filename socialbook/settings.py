# -----------------------------------------------------------------------------
# Email (used to send event-registration confirmation emails)
# -----------------------------------------------------------------------------
# Credentials are read from environment variables — NEVER hardcode a real
# email/password here, and never commit them to source control.
#
# To send real emails via Gmail:
#   1. Turn on 2-Step Verification on the Gmail account:
#        https://myaccount.google.com/security
#   2. Create an "App Password" for this Gmail account:
#        https://myaccount.google.com/apppasswords
#      (Regular Gmail passwords will NOT work with SMTP — you need this
#      16-character App Password instead.)
#   3. Before running the server, set these two environment variables:
#        Windows (PowerShell):
#          $env:EMAIL_HOST_USER = "youraddress@gmail.com"
#          $env:EMAIL_HOST_PASSWORD = "your16charapppassword"
#        macOS/Linux:
#          export EMAIL_HOST_USER="youraddress@gmail.com"
#          export EMAIL_HOST_PASSWORD="your16charapppassword"
#
# If these are left unset, EMAIL_BACKEND falls back to the console backend,
# so emails are printed to the terminal instead of actually being sent —
# useful for development without needing real credentials.

EMAIL_HOST_USER = os.environ.get('EMAIL_HOST_USER', '')
EMAIL_HOST_PASSWORD = os.environ.get('EMAIL_HOST_PASSWORD', '')

if EMAIL_HOST_USER and EMAIL_HOST_PASSWORD:
    EMAIL_BACKEND = 'django.core.mail.backends.smtp.EmailBackend'
    EMAIL_HOST = 'smtp.gmail.com'
    EMAIL_PORT = 587
    EMAIL_USE_TLS = True
else:
    EMAIL_BACKEND = 'django.core.mail.backends.console.EmailBackend'

DEFAULT_FROM_EMAIL = EMAIL_HOST_USER or 'noreply@srmcem-events.local'
